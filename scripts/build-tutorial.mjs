// Writes template/reference/strudel-tutorial.md from the workshop and the "learn" pages
// of strudel.cc, for an AI assistant that edits a song: how the language is meant to be
// used, with the examples of the site. The pages are fetched from the Strudel source at
// the commit of the packages we pin, so the examples match the engine that plays them.
//   pnpm tutorial
// Change COMMIT when the @strudel/* packages are updated (the tag is
// `@strudel/codemirror@<version>` on codeberg.org/uzu/strudel).
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const COMMIT = 'f610965f4332837febe45743105da170e8b331ed'; // @strudel/codemirror@1.3.0
const SOURCE = `https://codeberg.org/uzu/strudel/raw/commit/${COMMIT}/website/src/pages`;

// The order a person would read them in. Left out: pages about the website (faq, pwa),
// MIDI and OSC, which a webview cannot use (input-output, input-devices), Csound, which
// we do not load, phone sensors, and the other notations (mondo, Tidal).
